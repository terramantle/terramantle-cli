//! Render the desired file set from a [`Manifest`] (SCAFFOLD-PUBLISH-AUTH.md §2).
//!
//! Every file `init` writes / `upgrade` manages is produced here from the manifest
//! alone, so rendering is a pure, deterministic function of the manifest — the
//! precondition for `upgrade` being a real diff. Two classes of file exist:
//!
//! * [`FileClass::Managed`] — deterministic from the manifest (CI pipeline,
//!   CODEOWNERS, `terramate.tm.hcl`). `upgrade` re-renders and diffs these; each
//!   carries a provenance header so a user edit is detectable.
//! * [`FileClass::Once`] — a starting point the user owns and edits (skeleton
//!   `.tf`, stack definitions, tool configs). `init` creates them if absent;
//!   `upgrade` never rewrites or prunes them.
//!
//! ## Why the pipelines are templates on disk, not `format!` chains
//!
//! The v1 renderer built YAML by concatenating `push_str` calls. That is how a
//! pipeline calling `modules publish` without its required `--provider` flag
//! shipped: nothing in the source read like the file it produced. The templates
//! now live in `templates/` as the YAML they emit, with `{{PLACEHOLDER}}` holes,
//! so a reviewer reads the artefact rather than the machinery.
//!
//! ## What the per-stack backend is NOT
//!
//! For a Terramate repo, each stack's `_backend.tf` is generated by `terramate
//! generate`, not by this module. Those paths depend on what is on disk, and the
//! diff engine reconciles a fixed path list — it could never prune or update
//! them correctly. `init` writes the root `terramate.tm.hcl` and CI enforces
//! that the committed output matches it.

use std::path::PathBuf;

use crate::manifest::{
    Artefact, ChangeBase, CiAuth, Manifest, Structure, Terramate, VcsProvider,
    DEFAULT_TERRAMATE_VERSION,
};
use crate::pins;

/// How `upgrade` treats a generated file. See the module docs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileClass {
    /// Re-rendered and diffed on every `upgrade`.
    Managed,
    /// Created once by `init`; never rewritten or pruned.
    Once,
}

/// One file the scaffolder wants on disk.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the repo root.
    pub path: PathBuf,
    pub content: String,
    /// Template id recorded in the provenance header, e.g. `github/modules`.
    pub template: String,
    pub template_version: u32,
    pub class: FileClass,
}

/// Provenance header version; bump when a managed template's layout changes.
///
/// v2: OpenTofu-only pipelines, Terramate stacks, saved-plan apply, pinned
/// action digests.
pub const TEMPLATE_VERSION: u32 = 2;

/// The substring every managed file's provenance header carries. `upgrade` scans
/// for this to recognise files it owns — the lock-free replacement for a manifest
/// lock (§3): a marked file no longer in the desired set is pruned.
pub const PROVENANCE_MARKER: &str = "managed by terramantle · template=";

/// The default registry URL the templates reference (mirrors tm-config).
const DEFAULT_REGISTRY: &str = "https://registry.terramantle.dev";

/// terraform-docs release the modules pipeline installs so `modules publish`
/// can regenerate each README.
const TERRAFORM_DOCS_VERSION: &str = "0.24.0";

// ---- templates ------------------------------------------------------------

const T_GITHUB_WORKSPACES: &str = include_str!("templates/github_workspaces.yml");
const T_GITHUB_MODULES: &str = include_str!("templates/github_modules.yml");
const T_GITLAB_WORKSPACES: &str = include_str!("templates/gitlab_workspaces.yml");
const T_GITLAB_MODULES: &str = include_str!("templates/gitlab_modules.yml");
const T_GITHUB_LINT: &str = include_str!("templates/github_lint_steps.yml");
const T_GITLAB_LINT: &str = include_str!("templates/gitlab_lint_steps.yml");
const T_GITHUB_DOCS: &str = include_str!("templates/github_docs_steps.yml");
const T_GITLAB_DOCS: &str = include_str!("templates/gitlab_docs_steps.yml");
const T_GITHUB_PR_COMMENT: &str = include_str!("templates/github_pr_comment.yml");
const T_GITHUB_PLAN_SUMMARY: &str = include_str!("templates/github_plan_summary_upload.yml");
const T_TERRAMATE: &str = include_str!("templates/terramate.tm.hcl");

/// Substitute `{{KEY}}` holes. Unknown placeholders are left alone so a typo in
/// a template surfaces as a visible `{{TYPO}}` in the output (and in the golden
/// files) rather than as silently missing content.
fn subst(template: &str, vars: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (k, v) in vars {
        out = out.replace(&format!("{{{{{k}}}}}"), v);
    }
    out
}

/// `TF_TOKEN_<host>` with Terraform's host encoding: hyphen → `__`, dot → `_`
/// (hyphens first so the dot pass does not touch the inserted underscores).
///
/// Lives here rather than in the CLI because the generated pipelines assert on
/// these exact variable names; sharing one definition with `auth env
/// --terraform` is what stops CI checking for a variable the CLI never exports.
pub fn tf_token_var(host: &str) -> String {
    format!("TF_TOKEN_{}", host.replace('-', "__").replace('.', "_"))
}

/// The bare hostname of an API base URL (`https://host:port/path` → `host`).
fn host_of(api_url: &str) -> String {
    let after_scheme = api_url.split("://").nth(1).unwrap_or(api_url);
    after_scheme
        .split(['/', '?', '#'])
        .next()
        .unwrap_or(after_scheme)
        .split(':')
        .next()
        .unwrap_or(after_scheme)
        .to_string()
}

/// Every path a managed file could occupy across both VCS providers and artefact
/// types. `upgrade` checks these for prune candidates (a marked file here that the
/// current manifest no longer wants — e.g. the other VCS's pipeline after a switch,
/// or `terramate.tm.hcl` after Terramate is turned off).
pub fn candidate_managed_paths() -> Vec<PathBuf> {
    [
        ".github/workflows/terramantle.yml",
        ".gitlab-ci.yml",
        ".github/CODEOWNERS",
        ".gitlab/CODEOWNERS",
        "terramate.tm.hcl",
    ]
    .into_iter()
    .map(PathBuf::from)
    .collect()
}

/// Build the full desired file set for a manifest.
///
/// Excludes `terramantle.hcl` itself — that is user-owned config, written once by
/// `init` and never rewritten by `upgrade` (it is the *input*, not an output).
///
/// `skeleton` controls the example artefact. It is a starting point for an
/// empty repo, and actively harmful in a populated one: an `example` stack is
/// a *real* stack, so `terramate run` would plan and apply it alongside the
/// user's own. Callers pass `false` once the repo already has artefacts.
pub fn desired_files_with(m: &Manifest, skeleton_wanted: bool) -> Vec<GeneratedFile> {
    let mut files = Vec::new();
    files.push(ci_pipeline(m));
    files.push(codeowners(m));
    if let Some(t) = &m.terramate {
        files.push(terramate_config(m, t));
    }
    files.extend(tool_configs(m));
    if skeleton_wanted {
        files.extend(skeleton(m));
    }
    files
}

/// [`desired_files_with`] including the example artefact.
pub fn desired_files(m: &Manifest) -> Vec<GeneratedFile> {
    desired_files_with(m, true)
}

/// A `#`-commented provenance header. `Managed` files carry the
/// "generated, do not edit" contract; `Once` files get no header.
fn header(template: &str, class: FileClass) -> String {
    match class {
        FileClass::Managed => format!(
            "# {PROVENANCE_MARKER}{template} · v={TEMPLATE_VERSION}\n\
             # Generated by `terramantle init`; re-rendered by `terramantle upgrade`.\n\
             # Edits are overwritten — change terramantle.hcl and re-run `upgrade` instead.\n"
        ),
        FileClass::Once => String::new(),
    }
}

fn registry_url(m: &Manifest) -> &str {
    m.api_url.as_deref().unwrap_or(DEFAULT_REGISTRY)
}

// ---- CI pipeline ----------------------------------------------------------

/// The VCS-trust subject CI will present, so the template can name it in the
/// comment that explains a 401. GitHub matches `repo:owner/repo`; GitLab matches
/// `project_path:group/project`.
fn trust_subject_placeholder(vcs: VcsProvider) -> &'static str {
    match vcs {
        VcsProvider::Github => "repo:<owner>/<repo>",
        VcsProvider::Gitlab => "project_path:<group>/<project>",
    }
}

/// Values every pipeline template shares.
fn common_vars(m: &Manifest) -> Vec<(&'static str, String)> {
    let api = registry_url(m).to_string();
    let host = host_of(&api);
    let branch = m.ci.default_branch.clone();
    vec![
        ("ORG", m.org.clone()),
        ("API_URL", api.clone()),
        // CI OIDC tokens are minted for the registry audience; the worker binds
        // the bearer to it and rejects anything else.
        ("OIDC_AUDIENCE", api),
        ("BACKEND_HOST", host.clone()),
        ("DEFAULT_BRANCH", branch.clone()),
        // A concurrency group key cannot contain characters a ref can, so the
        // branch is slugged for that one use.
        ("DEFAULT_BRANCH_SLUG", slug(&branch)),
        ("RUNNER", m.ci.runner.clone()),
        ("TOFU_VERSION", m.ci.tofu_version().to_string()),
        (
            "TERRAMATE_VERSION",
            m.terramate
                .as_ref()
                .map(|t| t.version.clone())
                .unwrap_or_else(|| DEFAULT_TERRAMATE_VERSION.to_string()),
        ),
        ("CLI_VERSION", env!("CARGO_PKG_VERSION").to_string()),
        ("TFLINT_VERSION", pins::TFLINT_VERSION.to_string()),
        ("TERRAFORM_DOCS_VERSION", TERRAFORM_DOCS_VERSION.to_string()),
        ("CLI_INSTALLER_URL", cli_installer_url()),
        (
            "TRUST_SUBJECT",
            trust_subject_placeholder(m.vcs).to_string(),
        ),
        (
            "CHANGE_BASE_ALL",
            match m.ci.change_base {
                ChangeBase::All => "1".to_string(),
                ChangeBase::Auto => "0".to_string(),
            },
        ),
        ("TF_TOKEN_APEX_VAR", tf_token_var(&host)),
        (
            "TF_TOKEN_ORG_VAR",
            tf_token_var(&format!("{}.{host}", m.org)),
        ),
        ("USES_CHECKOUT", pins::CHECKOUT.uses()),
        ("USES_UPLOAD_ARTIFACT", pins::UPLOAD_ARTIFACT.uses()),
        ("USES_DOWNLOAD_ARTIFACT", pins::DOWNLOAD_ARTIFACT.uses()),
        ("USES_GITHUB_SCRIPT", pins::GITHUB_SCRIPT.uses()),
        ("USES_SETUP_OPENTOFU", pins::SETUP_OPENTOFU.uses()),
        ("USES_TERRAMATE", pins::TERRAMATE_ACTION.uses()),
        ("USES_SETUP_TFLINT", pins::SETUP_TFLINT.uses()),
    ]
}

/// The pinned release installer for the CLI. Versioned, never `latest`: a
/// pipeline that silently upgrades its own tooling is not reproducible.
fn cli_installer_url() -> String {
    format!(
        "https://github.com/terramantle/terramantle-cli/releases/download/v{}/cli-installer.sh",
        env!("CARGO_PKG_VERSION")
    )
}

/// Lowercase, non-alphanumerics to `-`. Only used for a concurrency group key.
fn slug(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect()
}

fn ci_pipeline(m: &Manifest) -> GeneratedFile {
    let (path, template, body) = match (m.vcs, m.artefact) {
        (VcsProvider::Github, Artefact::Workspaces) => (
            ".github/workflows/terramantle.yml",
            "github/workspaces",
            T_GITHUB_WORKSPACES,
        ),
        (VcsProvider::Github, Artefact::Modules) => (
            ".github/workflows/terramantle.yml",
            "github/modules",
            T_GITHUB_MODULES,
        ),
        (VcsProvider::Gitlab, Artefact::Workspaces) => {
            (".gitlab-ci.yml", "gitlab/workspaces", T_GITLAB_WORKSPACES)
        }
        (VcsProvider::Gitlab, Artefact::Modules) => {
            (".gitlab-ci.yml", "gitlab/modules", T_GITLAB_MODULES)
        }
    };

    // Conditional blocks first: they are themselves templates (a lint block
    // carries `{{USES_SETUP_TFLINT}}`, a docs block `{{TERRAFORM_DOCS_VERSION}}`),
    // so they must be spliced in before the scalar pass runs over the result.
    let mut vars = conditional_blocks(m);
    vars.extend(common_vars(m));

    let borrowed: Vec<(&str, &str)> = vars.iter().map(|(k, v)| (*k, v.as_str())).collect();
    let content = format!(
        "{}{}",
        header(template, FileClass::Managed),
        subst(body, &borrowed)
    );

    GeneratedFile {
        path: PathBuf::from(path),
        content,
        template: template.to_string(),
        template_version: TEMPLATE_VERSION,
        class: FileClass::Managed,
    }
}

/// The feature-gated blocks. A disabled feature renders as an empty string, so
/// the step simply is not there — never a commented-out stub, which reads as
/// something the user could switch on without also adding its config file.
fn conditional_blocks(m: &Manifest) -> Vec<(&'static str, String)> {
    let github = m.vcs == VcsProvider::Github;
    let lint = if !m.ci.lint {
        String::new()
    } else if github {
        T_GITHUB_LINT.to_string()
    } else {
        T_GITLAB_LINT.to_string()
    };
    let docs = if !m.ci.docs {
        String::new()
    } else if github {
        T_GITHUB_DOCS.to_string()
    } else {
        T_GITLAB_DOCS.to_string()
    };
    // The PR comment needs the summary artefact, so the two travel together.
    let (pr_comment, plan_summary) = if m.ci.pr_comment && github {
        (
            T_GITHUB_PR_COMMENT.to_string(),
            T_GITHUB_PLAN_SUMMARY.to_string(),
        )
    } else {
        (String::new(), String::new())
    };

    // GitLab has no secrets store the pipeline can assert against at render
    // time, so the required-variable list is part of the header comment.
    let mut required = String::new();
    if m.ci.lint {
        required.push_str(
            "#   GITHUB_TOKEN    (masked) — tflint plugin downloads; without it the job shares\n\
             #                   one anonymous 60/hr GitHub API quota by runner IP.\n",
        );
    }
    let tflint_var = if m.ci.lint {
        format!("  TFLINT_VERSION: \"{}\"\n", pins::TFLINT_VERSION)
    } else {
        String::new()
    };
    let tfdocs_var = if m.ci.docs {
        format!("  TFDOCS_VERSION: \"{TERRAFORM_DOCS_VERSION}\"\n")
    } else {
        String::new()
    };

    // ---- CI auth grant --------------------------------------------------
    //
    // OIDC is keyless: GitHub mints an ambient token (needs `id-token: write`),
    // GitLab mints one through `id_tokens:`. Bot is client-credentials from CI
    // secrets, and must NOT carry the OIDC permission — leaving it on would let
    // the CLI's auth detection pick the ambient token over the configured
    // credentials and fail confusingly.
    let oidc = m.ci.auth == CiAuth::Oidc;
    let gh_oidc_perm = if oidc {
        "      id-token: write\n".to_string()
    } else {
        String::new()
    };
    let gh_bot_env = if oidc {
        String::new()
    } else {
        "  # auth=bot: client credentials from repo secrets. The explicit auth mode\n\
         \x20 # stops detection falling through to the ambient GitHub OIDC token.\n\
         \x20 TERRAMANTLE_AUTH_MODE: client\n\
         \x20 TERRAMANTLE_CLIENT_ID: ${{ secrets.TERRAMANTLE_CLIENT_ID }}\n\
         \x20 TERRAMANTLE_CLIENT_SECRET: ${{ secrets.TERRAMANTLE_CLIENT_SECRET }}\n"
            .to_string()
    };
    let gitlab_auth_fragment = if oidc {
        format!(
            "# Job-level `id_tokens` does NOT merge with `default:id_tokens` — the job's\n\
             # definition wins outright. Keeping it in a hidden job pulled in by `extends:`\n\
             # avoids that trap, and means the `check` job gets no identity at all.\n\
             .ci_auth:\n  \
             id_tokens:\n    \
             TERRAMANTLE_ID_TOKEN:\n      \
             aud: \"{}\"\n",
            registry_url(m)
        )
    } else {
        "# auth=bot: client credentials from masked CI/CD variables\n\
         # (TERRAMANTLE_CLIENT_ID / TERRAMANTLE_CLIENT_SECRET on the project).\n\
         # The explicit mode stops detection falling through to GitLab OIDC.\n\
         .ci_auth:\n  \
         variables:\n    \
         TERRAMANTLE_AUTH_MODE: client\n"
            .to_string()
    };

    // The header has to describe the grant the file actually uses; a generated
    // comment explaining OIDC on a bot pipeline is worse than none.
    let github = m.vcs == VcsProvider::Github;
    let auth_note = match (oidc, github) {
        (true, true) => {
            "# Auth is keyless. `terramantle auth env --terraform` detects GITHUB_ACTIONS,\n\
             # mints the ambient OIDC token itself, and exports TF_HTTP_PASSWORD plus the\n\
             # TF_TOKEN_* registry credentials. The org must trust this repo under VCS\n\
             # Trust with subject `{{TRUST_SUBJECT}}` or every call 401s.\n"
        }
        (true, false) => {
            "# Auth is keyless. `terramantle auth env --terraform` detects GITLAB_CI, reads\n\
             # the JWT that `id_tokens:` minted, and exports TF_HTTP_PASSWORD plus the\n\
             # TF_TOKEN_* registry credentials. The org must trust this project under VCS\n\
             # Trust with subject `{{TRUST_SUBJECT}}` or every call 401s.\n"
        }
        (false, true) => {
            "# Auth uses bot client credentials, not OIDC. Set the repo secrets\n\
             # TERRAMANTLE_CLIENT_ID and TERRAMANTLE_CLIENT_SECRET (Settings → Secrets and\n\
             # variables → Actions). No VCS trust entry is needed for this grant.\n"
        }
        (false, false) => {
            "# Auth uses bot client credentials, not OIDC — self-managed GitLab cannot use\n\
             # keyless auth, because the registry trusts only the literal gitlab.com issuer.\n\
             # Set TERRAMANTLE_CLIENT_ID and TERRAMANTLE_CLIENT_SECRET as masked CI/CD\n\
             # variables. No VCS trust entry is needed for this grant.\n"
        }
    }
    .to_string();

    vec![
        ("AUTH_NOTE", auth_note),
        ("GH_OIDC_PERM", gh_oidc_perm),
        ("GH_BOT_ENV", gh_bot_env),
        ("GITLAB_AUTH_FRAGMENT", gitlab_auth_fragment),
        ("LINT_STEPS", lint),
        ("DOCS_STEPS", docs),
        ("PR_COMMENT_JOB", pr_comment),
        ("PLAN_SUMMARY_UPLOAD", plan_summary),
        ("GITLAB_REQUIRED_VARS", required),
        ("GITLAB_TFLINT_VAR", tflint_var),
        ("GITLAB_TFDOCS_VAR", tfdocs_var),
    ]
}

// ---- terramate.tm.hcl -----------------------------------------------------

fn terramate_config(m: &Manifest, t: &Terramate) -> GeneratedFile {
    let api = registry_url(m).to_string();
    let vars: Vec<(&str, String)> = vec![
        ("ORG", m.org.clone()),
        ("BACKEND_HOST", host_of(&api)),
        ("DEFAULT_BRANCH", m.ci.default_branch.clone()),
        ("WORKSPACE_EXPR", t.workspace_name.clone()),
    ];
    let borrowed: Vec<(&str, &str)> = vars.iter().map(|(k, v)| (*k, v.as_str())).collect();
    GeneratedFile {
        path: PathBuf::from("terramate.tm.hcl"),
        content: format!(
            "{}{}",
            header("terramate", FileClass::Managed),
            subst(T_TERRAMATE, &borrowed)
        ),
        template: "terramate".to_string(),
        template_version: TEMPLATE_VERSION,
        class: FileClass::Managed,
    }
}

// ---- .gitignore -----------------------------------------------------------

/// The ignore lines every terramantle repo needs.
///
/// `tfplan`/`tfplan.sha` are load-bearing, not tidiness: the apply job restores
/// plan files into the working tree and then runs `terramate run`, whose
/// `git-untracked` safeguard aborts the whole run — before the first stack — if
/// it finds untracked files. `.terramantle-ci/` is the GitLab plan bundle.
pub const GITIGNORE_LINES: &[&str] = &[
    ".terraform/",
    "*.tfstate",
    "*.tfstate.*",
    "tfplan",
    "tfplan.sha",
    ".terramantle-ci/",
];

/// Idempotently ensure the terramantle ignore lines are present in a `.gitignore`.
///
/// Returns `Some(new_content)` when a change is needed (missing lines appended
/// under a `# terramantle` marker), or `None` when the file already covers them —
/// so `upgrade` only rewrites `.gitignore` when it actually must. Unlike managed
/// files this is a *merge*, never a clobber: the user's own entries are preserved.
pub fn merge_gitignore(existing: Option<&str>) -> Option<String> {
    let current = existing.unwrap_or("");
    let present: std::collections::BTreeSet<&str> = current.lines().map(str::trim).collect();
    let missing: Vec<&str> = GITIGNORE_LINES
        .iter()
        .copied()
        .filter(|l| !present.contains(*l))
        .collect();
    if missing.is_empty() {
        return None;
    }
    let mut out = String::from(current);
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    if !out.is_empty() {
        out.push('\n');
    }
    out.push_str("# terramantle\n");
    for line in missing {
        out.push_str(line);
        out.push('\n');
    }
    Some(out)
}

// ---- CODEOWNERS -----------------------------------------------------------

fn codeowners(m: &Manifest) -> GeneratedFile {
    let (path, docs) = match m.vcs {
        VcsProvider::Github => (
            ".github/CODEOWNERS",
            "https://docs.github.com/articles/about-code-owners",
        ),
        VcsProvider::Gitlab => (
            ".gitlab/CODEOWNERS",
            "https://docs.gitlab.com/user/project/codeowners/",
        ),
    };
    // Scaffold-once, not managed: the owner is the user's to set, and
    // re-rendering it on every `upgrade` would stamp the placeholder back over
    // a real team. No provenance header for the same reason.
    let mut s = String::new();
    s.push_str("# Ownership stub. Replace the placeholder with a real team before enabling\n");
    s.push_str("# required reviews — an owner that does not exist blocks every merge.\n");
    s.push_str(&format!("# Docs: {docs}\n"));
    s.push_str("* @your-org/platform\n");
    GeneratedFile {
        path: PathBuf::from(path),
        content: s,
        template: "codeowners".to_string(),
        template_version: TEMPLATE_VERSION,
        class: FileClass::Once,
    }
}

// ---- tool configs (scaffold-once) -----------------------------------------

/// Config files the pipeline's optional steps require.
///
/// v1 enabled `lint`/`docs` in the manifest but never wrote their configs, so
/// the steps ran against defaults or failed outright. Both pipelines now assert
/// the file exists before running the tool, which makes writing them mandatory.
fn tool_configs(m: &Manifest) -> Vec<GeneratedFile> {
    let mut out = Vec::new();
    if m.ci.lint {
        out.push(once(
            ".tflint.hcl".to_string(),
            "# tflint configuration. Scaffolded by terramantle; yours to edit.\n\
             #\n\
             # In recursive mode tflint resolves a relative --config per directory, so CI\n\
             # passes this file as an absolute path and every stack shares it.\n\
             config {\n  \
             call_module_type = \"local\"\n\
             }\n\n\
             plugin \"terraform\" {\n  \
             enabled = true\n  \
             preset  = \"recommended\"\n\
             }\n"
            .to_string(),
        ));
    }
    if m.ci.docs && m.artefact == Artefact::Modules {
        out.push(once(
            ".terraform-docs.yml".to_string(),
            "# terraform-docs configuration. Scaffolded by terramantle; yours to edit.\n\
             # `terramantle modules publish` runs terraform-docs when it is on PATH and\n\
             # injects the result between the markers in each module README.\n\
             formatter: markdown table\n\n\
             output:\n  \
             file: README.md\n  \
             mode: inject\n  \
             template: |-\n    \
             <!-- BEGIN_TF_DOCS -->\n    \
             {{ .Content }}\n    \
             <!-- END_TF_DOCS -->\n\n\
             sort:\n  \
             enabled: true\n  \
             by: required\n"
                .to_string(),
        ));
    }
    out
}

// ---- Skeleton (scaffold-once) ---------------------------------------------

fn skeleton(m: &Manifest) -> Vec<GeneratedFile> {
    // Poly = one artefact at the repo root; mono = an example under the
    // discovery dir, named so the module convention is demonstrated.
    let base = match m.structure {
        Structure::Poly => String::new(),
        Structure::Mono => match m.artefact {
            Artefact::Modules => "modules/terraform-null-example/".to_string(),
            Artefact::Workspaces => "stacks/example/".to_string(),
        },
    };
    match m.artefact {
        Artefact::Modules => module_skeleton(&base),
        Artefact::Workspaces => workspace_skeleton(m, &base),
    }
}

fn once(path: String, content: String) -> GeneratedFile {
    GeneratedFile {
        path: PathBuf::from(path),
        content,
        template: "skeleton".to_string(),
        template_version: TEMPLATE_VERSION,
        class: FileClass::Once,
    }
}

fn module_skeleton(base: &str) -> Vec<GeneratedFile> {
    vec![
        once(
            format!("{base}main.tf"),
            "# Example module — replace with your resources.\n\
             #\n\
             # The directory name is the registry address: `terraform-<provider>-<name>`\n\
             # publishes as <org>/<name>/<provider>. Rename the directory to rename the\n\
             # module.\n"
                .to_string(),
        ),
        once(
            format!("{base}variables.tf"),
            "variable \"name\" {\n  description = \"Example input.\"\n  type        = string\n}\n"
                .to_string(),
        ),
        once(
            format!("{base}outputs.tf"),
            "output \"name\" {\n  description = \"Example output.\"\n  value       = var.name\n}\n"
                .to_string(),
        ),
        once(
            format!("{base}versions.tf"),
            "terraform {\n  required_version = \">= 1.7\"\n}\n".to_string(),
        ),
        once(
            format!("{base}README.md"),
            "# Example module\n\n<!-- BEGIN_TF_DOCS -->\n<!-- END_TF_DOCS -->\n".to_string(),
        ),
    ]
}

fn workspace_skeleton(m: &Manifest, base: &str) -> Vec<GeneratedFile> {
    let mut out = vec![once(
        format!("{base}main.tf"),
        "# Example stack — replace with your configuration.\n".to_string(),
    )];

    match &m.terramate {
        // Terramate owns the backend: the stack only declares itself, and
        // `terramate generate` writes `_backend.tf` beside it.
        Some(_) => out.push(once(
            format!("{base}stack.tm.hcl"),
            "stack {\n  \
             name        = \"example\"\n  \
             description = \"Example stack scaffolded by terramantle.\"\n\
             }\n\n\
             # `_backend.tf` beside this file is generated by `terramate generate` from the\n\
             # root terramate.tm.hcl. Do not edit it; edit the generate_hcl block instead.\n"
                .to_string(),
        )),
        // Without Terramate the backend is a plain scaffold-once file. All three
        // addresses are set: omitting lock_address disables locking entirely AND
        // skips the server-side state policy gate, which only runs on LOCK.
        None => {
            // The workspace name must equal the artefact directory's basename,
            // because `state publish` derives it from the directory. Both the
            // poly (repo root) and mono (`stacks/example/`) skeletons use the
            // example stack, so it is the same name either way.
            let ws = "example";
            out.push(once(
                format!("{base}backend.tf"),
                format!(
                    "terraform {{\n  \
                     backend \"http\" {{\n    \
                     # Terramantle HTTP state backend.\n    \
                     #\n    \
                     # lock_address/unlock_address are NOT optional: without them OpenTofu\n    \
                     # never issues LOCK, so concurrent applies do not exclude each other and\n    \
                     # the server-side state policy gate (LOCK-only) never runs.\n    \
                     #\n    \
                     # The backend ignores the username and reads the token from the password,\n    \
                     # supplied at runtime via TF_HTTP_PASSWORD.\n    \
                     address        = \"{reg}/state/{org}/{ws}\"\n    \
                     lock_address   = \"{reg}/state/{org}/{ws}.lock\"\n    \
                     unlock_address = \"{reg}/state/{org}/{ws}.lock\"\n    \
                     username       = \"terramantle-ci\"\n  \
                     }}\n\
                     }}\n",
                    reg = registry_url(m),
                    org = m.org,
                ),
            ));
        }
    }

    out.push(once(
        format!("{base}versions.tf"),
        "terraform {\n  required_version = \">= 1.7\"\n}\n".to_string(),
    ));
    out
}

