    /// grammar [`subst`] fills. Narrow on purpose: generated files legitimately
    /// contain other brace pairs — GitHub Actions' `${{ github.ref }}` and
    /// terraform-docs' `{{ .Content }}` — and neither is our syntax.
    fn has_unsubstituted(line: &str) -> bool {
        line.match_indices("{{").any(|(i, _)| {
            let rest = &line[i + 2..];
            match rest.find("}}") {
                Some(end) if end > 0 => rest[..end]
                    .chars()
                    .all(|c| c.is_ascii_uppercase() || c == '_'),
                _ => false,
            }
        })
    }

